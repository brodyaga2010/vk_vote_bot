def get_token() -> str:
    token = os.getenv("VK_BOT_TOKEN", "").strip()
    if not token:
        raise RuntimeError(
            "Не найден VK_BOT_TOKEN. Установите переменную окружения перед запуском."
        )
    return token


def get_admin_ids() -> set[int]:
    raw_value = os.getenv("VK_ADMIN_IDS", "").strip()
    if not raw_value:
        return set()

    admin_ids: set[int] = set()
    for chunk in raw_value.split(","):
        value = chunk.strip()
        if not value:
            continue
        if not value.isdigit():
            raise RuntimeError(
                "VK_ADMIN_IDS должен содержать только числовые VK ID через запятую."
            )
        admin_ids.add(int(value))
    return admin_ids
